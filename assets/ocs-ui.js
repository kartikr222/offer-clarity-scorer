/* OCS UI compatibility layer. The scorer renders its interface from ocs.js. */
(function(){
  'use strict';
  
  // Mark document as ready for CSS styling
  document.documentElement.classList.add('ocs-ready');
  
  // Add export functionality
  window.exportOCSResults = function(){
    const results = [];
    const scores = document.querySelectorAll('.ocs-dimension-score');
    const names = document.querySelectorAll('.ocs-dimension-name');
    
    scores.forEach((score, i) => {
      if(names[i]){
        results.push(`${names[i].textContent}: ${score.textContent}`);
      }
    });
    
    const composite = document.querySelector('.ocs-score');
    const timestamp = new Date().toLocaleString();
    
    const text = `Offer Clarity Score Results\n${timestamp}\n\n${composite?.textContent || 'Score not available'}\n\n${results.join('\n')}\n\nGenerated by Offer Clarity Scorer™`;
    
    const blob = new Blob([text], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `offer-clarity-score-${Date.now()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };
  
  // Hook export button
  document.addEventListener('DOMContentLoaded', function(){
    const exportBtn = document.getElementById('ocsExport');
    if(exportBtn){
      exportBtn.addEventListener('click', window.exportOCSResults);
    }
  });
})();
